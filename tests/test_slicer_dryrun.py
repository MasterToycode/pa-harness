"""Slicer dry run: the manufacturing layer must produce evidence, or say it could not.

What is pinned here
-------------------
* **Parsing** is a pure function over text, tested with fixed G-code fragments from
  three dialects (PrusaSlicer/OrcaSlicer comments, CuraEngine comments). A field whose
  comment is absent must stay `None` — an estimated time this module invented would be
  worse than no number at all.
* **The dry run** is exercised through a fake slicer: a Python script that accepts the
  PrusaSlicer CLI (`--export-gcode --output <file>`) and writes its own comments.
  `PAH_SLICER` points at `"<python>" "<script>"`, which is also how a real wrapper is
  installed, so the test does not need a slicer, a network or a platform launcher.
* **The gate** must only get stricter. A run that already failed the mesh/report gate
  stays unprintable even if the slicer succeeds; a run that passed it becomes
  unprintable when the slicer fails, and when no slicer exists at all.
* **C4's shape**: a part the slicer rejects (the fake's "fail" mode stands in for a
  0.2 mm wall the slicer cannot form) exports `printable: false` with the slicer's own
  words in `problems`.

Everything here is offline and finishes in seconds: the "slicer" is a script, and the
manifest checks read the returned dict rather than re-running the CLI.
"""

from __future__ import annotations

import json
import sys
import textwrap
from pathlib import Path

import pytest
import trimesh

from pah.cli.export import export_run
from pah.tools import slicer as slicer_module
from pah.tools.slicer import (
    Slicer,
    SlicerMissing,
    find_slicer,
    parse_slicer_output,
    slice_mesh,
)

# --------------------------------------------------------------------------- #
# Fixtures
# --------------------------------------------------------------------------- #
PRUSA_GCODE = """; estimated printing time (normal mode) = 1h 2m 3s
; filament used [mm] = 1234.50
; total layers count = 42
; support_material = 1
G1 X0 Y0 E1
"""

FAKE_SLICER = textwrap.dedent(
    '''
    """A fake slicer: writes the comment block a real one writes, or fails loudly."""
    import sys
    from pathlib import Path

    GCODE = """__GCODE__"""
    MODE = "__MODE__"

    args = sys.argv[1:]
    output = None
    if "--output" in args:
        output = args[args.index("--output") + 1]
    elif "-o" in args:
        output = args[args.index("-o") + 1]

    if MODE == "fail":
        print("error: mesh is not manifold; the slicer produced 0 printable layers", file=sys.stderr)
        raise SystemExit(2)
    if output is None:
        print("error: the fake slicer got no --output", file=sys.stderr)
        raise SystemExit(2)
    if MODE == "empty":
        # Exit 0 with a G-code file but none of the numbers the manifest needs.
        Path(output).write_text("; generated by the fake slicer\\nG1 X0 Y0\\n", encoding="utf-8")
        raise SystemExit(0)
    Path(output).write_text(GCODE, encoding="utf-8")
    raise SystemExit(0)
    '''
).strip()


def write_fake_slicer(tmp_path: Path, *, mode: str = "ok", gcode: str = PRUSA_GCODE) -> Path:
    """Writes the fake slicer script and returns its path."""
    script = tmp_path / "fake_slicer.py"
    source = (
        FAKE_SLICER.replace("__MODE__", mode)
        .replace("__GCODE__", gcode.replace("\\", "\\\\").replace('"""', '\\"\\"\\"'))
    )
    script.write_text(source, encoding="utf-8")
    return script


def use_fake_slicer(monkeypatch, script: Path) -> None:
    """Points `$PAH_SLICER` at `"<python>" "<script>"`.

    A quoted command line rather than a wrapper executable: it is the same mechanism a
    real install uses when the engine needs fixed arguments, and it works on Windows
    and POSIX without a `.cmd`/`.sh` launcher.
    """
    monkeypatch.setenv("PAH_SLICER", f'"{sys.executable}" "{script}"')


def write_run(tmp_path: Path, verdicts: dict, *, parts: int = 2) -> Path:
    """A run directory the export gate accepts as fully validated."""
    run = tmp_path / "run"
    geometry = run / "geometry"
    geometry.mkdir(parents=True)
    for name in ("left", "right")[:parts]:
        mesh = trimesh.creation.box(extents=(20.0, 20.0, 10.0))
        (geometry / f"{name}.stl").write_bytes(mesh.export(file_type="stl"))
    (run / "report.json").write_text(
        json.dumps(
            {
                "schema": "pah-run-report/2",
                "run": {"generator": "local-parametric"},
                "verdicts": verdicts,
            }
        ),
        encoding="utf-8",
    )
    return run


FULL = {
    "assemblable": {"ok": True, "validated": "full", "not_evaluated": [], "blocking": []},
    "printable": {
        "ok": True,
        "validated": "full",
        "not_evaluated": [],
        "blocking": [],
        "watertight": {"left": True, "right": True},
    },
}

PARTIAL = {
    "assemblable": {"ok": True, "validated": "full", "not_evaluated": [], "blocking": []},
    "printable": {
        "ok": True,
        "validated": "partial",
        "not_evaluated": ["printability"],
        "blocking": [],
        "watertight": {"left": True, "right": True},
    },
}


