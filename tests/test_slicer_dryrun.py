# Parsing: three dialects, missing fields stay missing
# --------------------------------------------------------------------------- #
def test_parse_prusaslicer_header():
    parsed = parse_slicer_output(PRUSA_GCODE)

    assert parsed["seconds_estimate"] == 3723  # 1h 2m 3s
    assert parsed["filament_mm"] == pytest.approx(1234.50)
    assert parsed["support_used"] is True
    assert parsed["layers"] == 42
    assert parsed["empty_layers"] == 0


def test_parse_orcaslicer_totals_and_tri_state_support():
    text = (
        "; estimated printing time (silent mode) = 2d 3h 4m 5s\n"
        "; total filament used [g] = 12.34\n"
        "; total filament used [mm] = 4100.5\n"
        "; total layers count = 7\n"
        "; support_material = nil\n"
    )
    parsed = parse_slicer_output(text)

    assert parsed["seconds_estimate"] == 2 * 86400 + 3 * 3600 + 4 * 60 + 5
    assert parsed["filament_g"] == pytest.approx(12.34)
    assert parsed["filament_mm"] == pytest.approx(4100.5)
    assert parsed["layers"] == 7
    # `nil` is "the slicer did not say", not "no supports": a false claim either way
    # would be wrong, so the field stays unknown.
    assert parsed["support_used"] is None


def test_parse_curaengine_comments():
    text = ";TIME:4020\n;Filament used: 1.23456m\n;LAYER_COUNT:42\n" + json.dumps(
        {"support_enable": "True"}
    )
    parsed = parse_slicer_output(text)

    assert parsed["seconds_estimate"] == 4020
    assert parsed["filament_mm"] == pytest.approx(1234.56)  # metres -> mm
    assert parsed["layers"] == 42
    assert parsed["support_used"] is True


def test_parse_reports_absence_as_none():
    parsed = parse_slicer_output("G1 X0 Y0\n; nothing useful here\n")

    assert parsed["seconds_estimate"] is None
    assert parsed["filament_mm"] is None
    assert parsed["filament_g"] is None
    assert parsed["support_used"] is None
    assert parsed["layers"] is None
    assert parsed["empty_layers"] == 0


def test_parse_counts_empty_layer_warnings():
    text = PRUSA_GCODE + "Warning: 2 empty layers detected; the object may be missing\n"
    assert parse_slicer_output(text)["empty_layers"] == 1


