def test_find_slicer_uses_pah_slicer_and_names_the_backend(monkeypatch, tmp_path):
    script = write_fake_slicer(tmp_path)
    use_fake_slicer(monkeypatch, script)

    found = find_slicer()

    assert found.backend == "custom"  # the interpreter's name says nothing
    assert found.path == sys.executable
    assert found.command[0] == sys.executable
    assert Path(found.command[1]) == script


def test_pah_slicer_named_executable_is_classified(monkeypatch, tmp_path):
    fake = tmp_path / "PrusaSlicer-console.exe"
    fake.write_text("", encoding="utf-8")
    monkeypatch.setenv("PAH_SLICER", str(fake))

    found = find_slicer()

    assert found.backend == "prusaslicer"
    assert found.command == [str(fake)]


def test_find_slicer_missing_is_named_and_actionable(monkeypatch):
    """Not installed must be a loud, named stop — never a silent pass."""
    monkeypatch.delenv("PAH_SLICER", raising=False)
    monkeypatch.setattr(slicer_module.shutil, "which", lambda _name: None)
    monkeypatch.setattr(slicer_module, "_WINDOWS_PATHS", ())

    with pytest.raises(SlicerMissing) as error:
        find_slicer()

    message = str(error.value)
    assert "no slicer found" in message
    assert "PAH_SLICER" in message
    assert "printable" in message  # it says what the consequence is


def test_pah_slicer_pointing_nowhere_is_an_error(monkeypatch, tmp_path):
    monkeypatch.setenv("PAH_SLICER", str(tmp_path / "not-installed-slicer.exe"))

    with pytest.raises(SlicerMissing) as error:
        find_slicer()

    assert "not-installed-slicer.exe" in str(error.value)


