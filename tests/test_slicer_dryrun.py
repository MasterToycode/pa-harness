def test_export_with_slice_appends_evidence_and_keeps_the_gcode(monkeypatch, tmp_path):
    script = write_fake_slicer(tmp_path)
    use_fake_slicer(monkeypatch, script)
    run = write_run(tmp_path, FULL)
    out = tmp_path / "print"

    manifest = export_run(run, out=out, slice=True)

    assert manifest["printable"] is True
    slicing = manifest["slicing"]
    assert slicing["ok"] is True
    assert slicing["backend"] == "custom"
    assert slicing["problems"] == []
    assert set(slicing["per_part"]) == {"left", "right"}
    assert slicing["per_part"]["left"]["seconds_estimate"] == 3723
    # The dry run's scratch directory is gone; the manifest must point at a kept file.
    gcode = Path(slicing["per_part"]["left"]["gcode_path"])
    assert gcode.exists()
    assert gcode == (out / "gcode" / "left.gcode").resolve()
    assert (out / "left.stl").exists()
    assert json.loads((out / "print-manifest.json").read_text("utf-8"))["slicing"]["ok"] is True


def test_export_without_slice_keeps_the_old_gate_unchanged(monkeypatch, tmp_path):
    """The new key must not be able to *relax* an old refusal."""
    monkeypatch.delenv("PAH_SLICER", raising=False)
    run = write_run(tmp_path, FULL)

    manifest = export_run(run)

    assert manifest["slicing"] is None
    assert manifest["printable"] is True
    assert not (Path(manifest["_run"]) / "print" / "gcode").exists()


def test_a_missing_slicer_makes_the_manifest_unprintable(monkeypatch, tmp_path):
    """The audit's rule: "not installed" is not "nothing to object to"."""
    monkeypatch.delenv("PAH_SLICER", raising=False)
    monkeypatch.setattr(slicer_module.shutil, "which", lambda _name: None)
    monkeypatch.setattr(slicer_module, "_WINDOWS_PATHS", ())
    run = write_run(tmp_path, FULL)

    manifest = export_run(run, out=tmp_path / "print", slice=True)

    assert manifest["printable"] is False
    assert manifest["slicing"]["ok"] is False
    assert manifest["slicing"]["backend"] is None
    assert manifest["slicing"]["per_part"] == {}
    assert any("no slicer found" in problem for problem in manifest["problems"])


def test_a_slicer_rejection_makes_the_manifest_unprintable(monkeypatch, tmp_path):
    """C4's mechanism: the slicer refuses (a 0.2 mm wall would fail this way) and the
    manifest says false with the slicer's own diagnosis."""
    script = write_fake_slicer(tmp_path, mode="fail")
    use_fake_slicer(monkeypatch, script)
    run = write_run(tmp_path, FULL)
    out = tmp_path / "print"

    manifest = export_run(run, out=out, slice=True)

    assert manifest["readiness"]["printable"]["ok"] is True  # the old gate passed
    assert manifest["printable"] is False  # the manufacturing gate did not
    assert manifest["slicing"]["ok"] is False
    joined = " | ".join(manifest["problems"])
    assert "left: the slicer exited 2" in joined
    assert "not manifold" in joined
    assert not (out / "gcode").exists() or not any((out / "gcode").iterdir())


def test_slicer_success_cannot_rescue_a_partial_report(monkeypatch, tmp_path):
    """Only append: a report that did not fully validate stays a refusal."""
    script = write_fake_slicer(tmp_path)
    use_fake_slicer(monkeypatch, script)
    run = write_run(tmp_path, PARTIAL)

    manifest = export_run(run, out=tmp_path / "print", slice=True)

    assert manifest["slicing"]["ok"] is True
    assert manifest["printable"] is False
    assert any("partial" in reason for reason in manifest["readiness"]["printable"]["reasons"])


def test_for_print_refuses_before_writing_when_the_slicer_fails(monkeypatch, tmp_path):
    """`--for-print` decides after slicing: a refused export leaves no artifact."""
    from pah.cli.main import main

    script = write_fake_slicer(tmp_path, mode="fail")
    use_fake_slicer(monkeypatch, script)
    run = write_run(tmp_path, FULL)
    out = tmp_path / "print"

    code = main(["export", str(run), "--slice", "--for-print", "--out", str(out)])

    assert code == 3
    assert not out.exists() or not any(out.iterdir())


def test_a_declared_slice_profile_is_recorded(monkeypatch, tmp_path):
    """A dry run with defaults and one with a project profile are different
    experiments; the manifest has to say which one produced the numbers."""
    script = write_fake_slicer(tmp_path)
    use_fake_slicer(monkeypatch, script)
    profile = tmp_path / "project.ini"
    profile.write_text("[print]\nfirst_layer_height = 0.2\n", encoding="utf-8")
    run = write_run(tmp_path, FULL)

    manifest = export_run(
        run, out=tmp_path / "print", slice=True, slice_profile=profile
    )

    assert manifest["slicing"]["profile"] == str(profile)
    assert manifest["slicing"]["ok"] is True
    assert manifest["printable"] is True


def test_cli_export_passes_the_slice_profile(monkeypatch, tmp_path):
    from pah.cli.main import main

    script = write_fake_slicer(tmp_path)
    use_fake_slicer(monkeypatch, script)
    profile = tmp_path / "project.ini"
    profile.write_text("[print]\n", encoding="utf-8")
    run = write_run(tmp_path, FULL)
    out = tmp_path / "print"

    code = main(
        ["export", str(run), "--slice", "--slice-profile", str(profile), "--out", str(out)]
    )

    assert code == 0
    manifest = json.loads((out / "print-manifest.json").read_text("utf-8"))
    assert manifest["slicing"]["profile"] == str(profile)


def test_cli_export_slice_prints_the_dry_run_line(monkeypatch, tmp_path, capsys):
    from pah.cli.main import main

    script = write_fake_slicer(tmp_path)
    use_fake_slicer(monkeypatch, script)
    run = write_run(tmp_path, FULL)

    code = main(["export", str(run), "--slice", "--out", str(tmp_path / "print")])

    assert code == 0
    output = capsys.readouterr().out
    assert "slicing" in output
    assert "3723s" in output
    assert "1234.5 mm filament" in output
