def test_slice_mesh_records_the_numbers_and_the_gcode(monkeypatch, tmp_path):
    script = write_fake_slicer(tmp_path)
    use_fake_slicer(monkeypatch, script)
    stl = tmp_path / "left.stl"
    stl.write_bytes(trimesh.creation.box(extents=(10.0, 10.0, 5.0)).export(file_type="stl"))

    result = slice_mesh(stl, tmp_path / "gcode")

    assert result.ok is True
    assert result.backend == "custom"
    assert result.seconds_estimate == 3723
    assert result.filament_mm == pytest.approx(1234.5)
    assert result.support_used is True
    assert result.layers == 42
    assert result.empty_layers == 0
    assert result.problems == ()
    assert result.gcode_path is not None
    assert Path(result.gcode_path).exists()


def test_slice_mesh_reports_a_failed_slice_in_its_own_words(monkeypatch, tmp_path):
    script = write_fake_slicer(tmp_path, mode="fail")
    use_fake_slicer(monkeypatch, script)
    stl = tmp_path / "thin.stl"
    stl.write_bytes(trimesh.creation.box(extents=(20.0, 20.0, 0.2)).export(file_type="stl"))

    result = slice_mesh(stl, tmp_path / "gcode")

    assert result.ok is False
    assert result.gcode_path is None
    joined = " | ".join(result.problems)
    assert "exited 2" in joined
    assert "not manifold" in joined
    assert "no G-code" in joined


def test_a_slicer_that_reports_none_of_the_numbers_is_not_evidence(monkeypatch, tmp_path):
    """Exit 0 is not enough: the audit needs time and material in the manifest."""
    script = write_fake_slicer(tmp_path, mode="empty")
    use_fake_slicer(monkeypatch, script)
    stl = tmp_path / "left.stl"
    stl.write_bytes(trimesh.creation.box(extents=(10.0, 10.0, 5.0)).export(file_type="stl"))

    result = slice_mesh(stl, tmp_path / "gcode")

    assert result.ok is False
    joined = " | ".join(result.problems)
    assert "no estimated printing time" in joined
    assert "no filament usage" in joined
    assert "no layer count" in joined
    assert result.seconds_estimate is None


def test_slice_mesh_without_a_slicer_raises(monkeypatch, tmp_path):
    monkeypatch.delenv("PAH_SLICER", raising=False)
    monkeypatch.setattr(slicer_module.shutil, "which", lambda _name: None)
    monkeypatch.setattr(slicer_module, "_WINDOWS_PATHS", ())
    stl = tmp_path / "left.stl"
    stl.write_bytes(trimesh.creation.box().export(file_type="stl"))

    with pytest.raises(SlicerMissing):
        slice_mesh(stl, tmp_path / "gcode")


